"""Bundle the wallpapers into src/wallpapers.h.

    python3 tools/gen_wallpapers.py

Reads assets/wallpapers/*.jpg (baseline JPEG, 640x360) in the order listed
in WALLPAPERS and writes each file's bytes plus a 16-color palette chosen by
median cut over the photo. The kernel loads that palette into the wallpaper
slots when the theme changes, then dithers the decoded photo against the
whole palette. Only the header is needed to build.
"""
import pathlib
import sys

from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import palette  # noqa: E402

ROOT = palette.ROOT
# (file stem, display name, credit) in theme order.
WALLPAPERS = [
    ("aqua", "Aqua", "Drawn by tools/gen_aqua_wallpaper.py"),
    ("lake", "Lake", "Photo on Unsplash: unsplash.com/photos/1501785888041-af3ef285b470"),
    ("clouds", "Clouds", "Photo on Unsplash: unsplash.com/photos/1506905925346-21bda4d32df4"),
]


def main():
    lines = ["/* Generated by tools/gen_wallpapers.py from the JPEGs in assets/wallpapers. Do not edit. */",
             "#ifndef WALLPAPERS_H", "#define WALLPAPERS_H", "#include <stdint.h>", "",
             f"#define WALLPAPER_N {len(WALLPAPERS)}", "#define WALLPAPER_COLORS 16", "",
             "typedef struct { const char *name; const char *credit; const uint8_t *jpeg; unsigned bytes; uint32_t colors[WALLPAPER_COLORS]; } Wallpaper;", "",
             "#ifdef WALLPAPERS_DEFINE_DATA"]
    table = []
    for stem, name, credit in WALLPAPERS:
        path = ROOT / "assets/wallpapers" / f"{stem}.jpg"
        data = path.read_bytes()
        im = Image.open(path).convert("RGB")
        im.thumbnail((160, 90))
        colors = palette.median_cut(list(im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()), 16)
        while len(colors) < 16:
            colors.append(colors[-1])
        lines.append(f"static const uint8_t wall_{stem}[{len(data)}] = {{")
        for i in range(0, len(data), 32):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
        lines.append("};")
        table.append(f'    {{"{name}", "{credit}", wall_{stem}, {len(data)}, {{'
                     + ", ".join(f"0x{(r << 16) | (g << 8) | b:06X}" for r, g, b in colors) + "}},")
        print(f"{stem}: {len(data)} bytes, {im.size} thumbnail, {len(colors)} colors")
    lines += ["static const Wallpaper wallpapers[WALLPAPER_N] = {", *table, "};", "#endif", "", "#endif", ""]
    (ROOT / "src/wallpapers.h").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
