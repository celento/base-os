"""Rasterize the SVG icon set into src/app_icons.h.

    python3 tools/gen_app_icons.py [--sheet preview.png]

Needs Playwright's Chromium (PLAYWRIGHT_MODULE may point at the module) and
Pillow; normal builds only need the committed header. Icons are rendered at
4x and box-filtered down to the big (desktop, app launcher) and small (taskbar,
lists) sizes, then quantized to the runtime palette plus a 48-color icon
palette chosen from the set itself. Each pixel stores a palette index and a
4-bit alpha so icons blend over wallpaper and chrome alike.
"""
import argparse
import os
import pathlib
import subprocess
import sys
import tempfile

from PIL import Image

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import icon_art  # noqa: E402
import palette  # noqa: E402

ROOT = palette.ROOT
BIG, SMALL, SS = 36, 18, 4


def render(names, size, work):
    files = [str(ROOT / "assets/icons" / f"{n}.svg") for n in names]
    env = dict(os.environ)
    env.setdefault("PLAYWRIGHT_MODULE", "playwright")
    subprocess.run(["node", str(ROOT / "tools/svg_render.js"), str(work), str(size * SS), *files], check=True, env=env)
    out = []
    for n in names:
        im = Image.open(work / f"{n}-{size * SS}.png").convert("RGBA")
        # Premultiply before filtering so transparent pixels do not bleed color.
        px = im.load()
        pre = Image.new("RGBA", im.size)
        pp = pre.load()
        for y in range(im.height):
            for x in range(im.width):
                r, g, b, a = px[x, y]
                pp[x, y] = (r * a // 255, g * a // 255, b * a // 255, a)
        small = pre.resize((size, size), Image.BOX)
        sp = small.load()
        for y in range(size):
            for x in range(size):
                r, g, b, a = sp[x, y]
                if a:
                    sp[x, y] = (min(255, r * 255 // a), min(255, g * 255 // a), min(255, b * 255 // a), a)
        out.append(small)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sheet", type=pathlib.Path)
    args = parser.parse_args()
    names = icon_art.write_all()
    with tempfile.TemporaryDirectory() as temp:
        work = pathlib.Path(temp)
        big = render(names, BIG, work)
        small = render(names, SMALL, work)

    fixed = palette.fixed_palette()
    samples = []
    for im in big + small:
        for r, g, b, a in (im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()):
            if a >= 160:
                samples.append((r, g, b))
    # The icon palette fills in what the fixed entries lack: drop candidates
    # already matched closely by a fixed color, then median-cut the rest.
    far = [p for p in samples if palette.distance((p[0] << 16) | (p[1] << 8) | p[2],
                                                  fixed[palette.nearest(fixed, (p[0] << 16) | (p[1] << 8) | p[2])]) > 900]
    icon_colors = palette.median_cut(far or samples, palette.PAL_ICON_N)
    while len(icon_colors) < palette.PAL_ICON_N:
        icon_colors.append(icon_colors[-1])
    colors = dict(fixed)
    for i, (r, g, b) in enumerate(icon_colors):
        colors[palette.PAL_ICON + i] = (r << 16) | (g << 8) | b

    cache = {}

    def quantize(im):
        size = im.width
        indices, alphas = [], []
        for r, g, b, a in (im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()):
            level = (a * 15 + 127) // 255
            if level == 0:
                indices.append(0)
                alphas.append(0)
                continue
            key = (r >> 2, g >> 2, b >> 2)
            if key not in cache:
                cache[key] = palette.nearest(colors, (r << 16) | (g << 8) | b)
            indices.append(cache[key])
            alphas.append(level)
        packed = [(alphas[i] << 4) | alphas[i + 1] for i in range(0, size * size, 2)]
        return indices + packed

    lines = ["/* Generated by tools/gen_app_icons.py from the SVG set in assets/icons. Do not edit.",
             " * Per icon: size*size palette indices, then size*size/2 bytes of 4-bit alpha. */",
             "#ifndef APP_ICONS_H", "#define APP_ICONS_H", "#include <stdint.h>", "",
             f"#define AI_BIG {BIG}", f"#define AI_SMALL {SMALL}", "", "enum {"]
    lines += [f"    AI_{n.upper().rstrip('_')}," for n in names]
    lines += ["    AI_COUNT", "};", "", "#ifdef APP_ICONS_DEFINE_DATA",
              f"static const uint32_t app_icon_palette[{palette.PAL_ICON_N}] = {{"]
    lines.append("    " + ", ".join(f"0x{colors[palette.PAL_ICON + i]:06X}" for i in range(palette.PAL_ICON_N)))
    lines += ["};", f"static const uint8_t app_icon_big[AI_COUNT][{BIG * BIG * 3 // 2}] = {{"]
    for n, im in zip(names, big):
        lines.append(f"    /* {n} */ {{{','.join(str(v) for v in quantize(im))}}},")
    lines += ["};", f"static const uint8_t app_icon_small[AI_COUNT][{SMALL * SMALL * 3 // 2}] = {{"]
    for n, im in zip(names, small):
        lines.append(f"    /* {n} */ {{{','.join(str(v) for v in quantize(im))}}},")
    lines += ["};", "#endif", "", "#endif", ""]
    (ROOT / "src/app_icons.h").write_text("\n".join(lines))

    if args.sheet:
        cols, cell = 9, BIG + SMALL + 14
        rows = (len(names) + cols - 1) // cols
        sheet = Image.new("RGB", (cols * cell, rows * (BIG + 10)), (236, 240, 246))
        for i, (b, s) in enumerate(zip(big, small)):
            x, y = (i % cols) * cell + 4, (i // cols) * (BIG + 10) + 4
            sheet.paste(preview(b, colors), (x, y))
            sheet.paste(preview(s, colors), (x + BIG + 4, y + BIG - SMALL))
        sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(args.sheet)
    print(f"Wrote {len(names)} icons at {BIG} and {SMALL} px with {palette.PAL_ICON_N} icon colors to src/app_icons.h")


def preview(im, colors):
    """What the kernel will draw over a light surface."""
    size = im.width
    out = Image.new("RGB", (size, size), (236, 240, 246))
    op = out.load()
    data = list(im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata())
    for y in range(size):
        for x in range(size):
            r, g, b, a = data[y * size + x]
            level = (a * 15 + 127) // 255
            if not level:
                continue
            c = colors[palette.nearest(colors, (r << 16) | (g << 8) | b)]
            cr, cg, cb = (c >> 16) & 255, (c >> 8) & 255, c & 255
            br, bg, bb = op[x, y]
            t = level * 17
            op[x, y] = (br + (cr - br) * t // 255, bg + (cg - bg) * t // 255, bb + (cb - bb) * t // 255)
    return out


if __name__ == "__main__":
    main()
